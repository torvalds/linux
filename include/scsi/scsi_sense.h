/*
 * Use this to build non-standard sense codes.
 * Note: this is defined as a macro instead of an inline function so that it can
 * be used to define SCSI failures array variables (see struct scsi_failure).
 */
#define scsi_sense_code(asc, ascq)	\
	((((asc) & 0xff) << 8) | ((ascq) & 0xff))

static inline u8 scsi_sense_code_asc(u16 code)
{
	return (code >> 8) & 0xff;
}

static inline u8 scsi_sense_code_ascq(u16 code)
{
	return code & 0xff;
}

