static int rppx1_bdrgb_probe(struct rpp_module *mod)
{
	/* Version check. */
	switch (rpp_module_read(mod, RGBDENOISE_VERSION_REG)) {
	case 6:
		/* 12-bit. */
		break;
	default:
		return -EINVAL;
	}

	return 0;
}

const struct rpp_module_ops rppx1_bdrgb_ops = {
	.probe = rppx1_bdrgb_probe,
};
